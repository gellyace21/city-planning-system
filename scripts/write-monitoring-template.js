const fs = require('fs');
const path = require('path');
const src = path.resolve(__dirname, 'projmonit2.b64');
const dest = path.resolve(__dirname, '..', 'lib', 'monitoringTemplateBase64.ts');
const b64 = fs.readFileSync(src, 'utf8').trim();
const chunkSize = 2000;
const parts = [];
for (let i = 0; i < b64.length; i += chunkSize) parts.push(b64.slice(i, i + chunkSize));
const out = `// Auto-generated by scripts/write-monitoring-template.js
// Canonical base64 taken from scripts/projmonit2.b64
const PARTS = [\n${parts.map(p => JSON.stringify(p)).join(',\n')}\n];

export const MONITORING_TEMPLATE_BASE64 = PARTS.join("");
export default MONITORING_TEMPLATE_BASE64;
`;
fs.writeFileSync(dest, out, 'utf8');
console.log('Wrote', dest, 'with', parts.length, 'parts.');
